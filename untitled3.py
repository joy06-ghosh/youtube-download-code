import yt_dlp
from google.colab import files

# Enter the YouTube video URL
video_url = input("Paste your YouTube video URL: ").strip()

if not video_url.startswith(("https://www.youtube.com/", "https://youtu.be/",
                             "https://youtube.com/", "https://m.youtube.com/")):
    raise ValueError("Please enter a valid YouTube video URL.")

# Download settings
ydl_opts = {
    "format": "bestvideo+bestaudio/best",  # Fallback to combined best format if separate streams are unavailable
    "outtmpl": "/content/%(title)s.%(ext)s",
    "noplaylist": True,
}

try:
    with yt_dlp.YoutubeDL(ydl_opts) as ydl:
        info = ydl.extract_info(video_url, download=True)
        filename = ydl.prepare_filename(info)

    print(f"Download complete: {info.get('title', 'Video')}")
    files.download(filename)

except Exception as e:
    print(f"Download failed: {e}")

